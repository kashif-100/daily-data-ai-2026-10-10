"""
ai_insights.py — auto-generates a plain-English narrative of the key
findings from findings.json (written by analysis.py).

This is the "AI integrated" part of the project: instead of a human
analyst writing the summary, the report is produced programmatically
from the data and the model's outputs.

Run:  python ai_insights.py
"""

import json
from datetime import date

with open("findings.json") as f:
    F = json.load(f)

m = F["classifier_metrics"]
n = F["n_reviews"]
pos_pct = F["sentiment_share"]["positive"] * 100
neg_pct = F["sentiment_share"]["negative"] * 100
neu_pct = F["sentiment_share"]["neutral"] * 100

worst = F["worst_category"]
worst_rate = F["worst_category_negative_rate"] * 100
best = F["best_category"]
best_rating = F["best_category_avg_rating"]

# Worst-month check: month with the lowest positive share
monthly = F["monthly_sentiment_share"]["positive"]
worst_month = min(monthly, key=monthly.get)
worst_month_pos = monthly[worst_month] * 100

# Partial-month caveat: the dataset ends on 2026-10-09, so October's
# monthly share is based on only 9 days of reviews and should not be
# over-read.
partial_month_note = (
    f" (note: {worst_month} is a partial month — the dataset ends on "
    f"{F['date_range'][1]} — so treat this dip with caution)"
    if worst_month == "2026-10" else ""
)

praise = ", ".join(f'"{w}"' for w in F["top_positive_words"][:8])
gripes = ", ".join(f'"{w}"' for w in F["top_negative_words"][:8])

complaint_lines = []
for c in F["top_complaints"]:
    complaint_lines.append(
        f"- **{c['product_name']}** ({c['rating']}★, {c['helpful_votes']} found it helpful): "
        f"\"{c['review_text'][:160]}…\""
    )
complaints_md = "\n".join(complaint_lines)

report = f"""# AI-Generated Insights — Review Sentiment Analyzer

*Auto-generated by `ai_insights.py` on {date.today().isoformat()} from
`findings.json`. No human wrote this summary — it was produced from the
data and the trained model.*

## Headline

Out of **{n:,} customer reviews**, **{pos_pct:.1f}% are positive** and
**{neg_pct:.1f}% are negative** ({neu_pct:.1f}% neutral 3-star reviews).
The storefront leans positive overall, but nearly one review in four is a
complaint — a clear signal that product quality and fulfillment still need
attention.

## What customers praise

The model's strongest positive signals read like a checklist of what the
store does right: {praise}. In plain terms, shoppers consistently praise
**build quality, ease of use, fast delivery, and value for money**.
These themes show up across all five categories, so they are brand
strengths, not one-product luck.

## What customers complain about

The strongest negative signals are: {gripes}. The recurring complaint
pattern is **products that stop working or arrive defective, poor build
quality, and unhelpful customer support**. Price is a secondary theme —
shoppers do not mind paying, but they expect the quality to match.

## Category spotlight

- **Needs attention: {worst}** — {worst_rate:.1f}% of its reviews are
  negative, the highest of any category. If support resources are limited,
  start here: investigate returns and defect rates for this line.
- **Doing well: {best}** — average rating **{best_rating:.2f}/5**, the
  highest in the catalog. Study what this category does right (packaging,
  quality control, listing accuracy) and copy it to the others.

## Trend over time

The weakest month was **{worst_month}**, when positive reviews dipped to
{worst_month_pos:.1f}% of that month's reviews{partial_month_note}. The overall trend is
stable rather than deteriorating, but the monthly wobble is a reminder to
keep monitoring — a two-month slide should trigger a quality review.

## The classifier behind this report

A TF-IDF + LogisticRegression model predicts positive vs negative
sentiment from review text with **accuracy {m['accuracy']:.1%},
F1 {m['f1']:.3f}, ROC-AUC {m['roc_auc']:.3f}** on a held-out test set of
{m['n_test']:,} reviews. In practice this means the store can
**auto-route incoming reviews**: flag strongly negative ones for the
support team within minutes instead of waiting for a manual read.

## Recommended actions (priority order)

1. **Fix {worst} first.** Audit its top-returned SKUs for defects and
   tighten quality control before the next stock order.
2. **Route negative reviews to support automatically** using the
   classifier — reply within 24 hours; a fast response turns 1-star
   reviewers into repeat buyers.
3. **Publish the fixes.** Respond publicly to the most-voted complaints
   (below) and state what changed — shoppers reward visible improvement.
4. **Keep doing what earns praise**: fast, well-packed delivery and
   honest listings. These drive the positive reviews that convert new
   buyers.

## Most-voted complaints (read these first)

{complaints_md}
"""

with open("AI_INSIGHTS.md", "w") as f:
    f.write(report)

print("AI_INSIGHTS.md written")
